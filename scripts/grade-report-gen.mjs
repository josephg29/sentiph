// Reusable grade report generator. Reads a JSON spec on argv[2], writes HTML to argv[3].
// Spec: { title, timestamp, mode:"everything", overallLabel, overallGrade, overallScore,
//         summary, progression:[{round,score,delta,neg}], categories:[
//           { name, letter, score, aspects:[{name,letter,score,good,improve}], fixes:[..] } ] }
import { readFileSync, writeFileSync } from "node:fs";

const spec = JSON.parse(readFileSync(process.argv[2], "utf8"));
const out = process.argv[3];
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const code = (s) => esc(s).replace(/`([^`]+)`/g, "<code>$1</code>");

const aspectCard = (a) => `
      <div class="aspect-card">
        <div class="aspect-header">
          <span class="aspect-name">${esc(a.name)}</span>
          <span class="aspect-grade grade-${a.letter}">[${a.letter}]<span class="num">${a.score}</span></span>
        </div>
        <div class="aspect-body">
          <div class="aspect-section good"><span class="aspect-label">+ good</span><p>${code(a.good)}</p></div>
          <div class="aspect-section improve"><span class="aspect-label">! improve</span><p>${code(a.improve)}</p></div>
        </div>
      </div>`;

const categoryBlock = (c) => `
  <section class="category">
    <header class="category-header"><div class="bar-dots"><span></span><span></span><span></span></div>
      <span class="category-file">${esc(c.name)}-report.html</span></header>
    <div class="category-overall">
      <div class="cat-grade grade-${c.letter}">[${c.letter}]</div>
      <div class="cat-meta"><h2>${esc(c.name)}</h2><div class="score">${c.score} / 100 · avg of 6 fine aspect scores</div></div>
    </div>
    <div class="aspects-grid">${c.aspects.map(aspectCard).join("")}</div>
    <div class="fixes-section"><h3># fixes (prioritized)</h3><ol>${c.fixes.map((f) => `<li>${code(f)}</li>`).join("")}</ol></div>
  </section>`;

const progression = spec.progression?.length
  ? `<section class="progression"><h3># score progression (reconciled fine scores)</h3>
      <div class="progression-rows">${spec.progression
        .map(
          (r) => `
        <div class="progression-row"><span class="round">${esc(r.round)}</span>
          <span class="bar"><span class="bar-fill" style="width:${r.score}%"></span></span>
          <span class="val">${r.score}</span>
          <span class="delta${r.neg ? " neg" : ""}">${esc(r.delta)}</span></div>`,
        )
        .join("")}</div>
      ${spec.noiseNote ? `<p style="margin-top:14px;font-size:12px;color:var(--accent-dim)">${esc(spec.noiseNote)}</p>` : ""}</section>`
  : "";

const tpl = readFileSync(
  "/Users/josephgannon/.claude/skills/grade/assets/report-template.html",
  "utf8",
);
// We only borrow the <style> block from the template to stay on-theme, but build body ourselves.
const style = tpl.slice(tpl.indexOf("<style>"), tpl.indexOf("</style>") + 8);

const html = `<!DOCTYPE html><html lang="en"><head><meta charset="UTF-8" />
<meta name="viewport" content="width=device-width, initial-scale=1.0" /><title>${esc(spec.title)}</title>
${style}<style>.aspect-grade .num{font-size:11px;color:var(--accent-dim);margin-left:6px}</style></head>
<body><div class="container">
  <header class="report-header"><div class="eyebrow">codebase report card</div>
    <h1>${esc(spec.title)}</h1><div class="timestamp">${esc(spec.timestamp)}</div></header>
  <div class="overall"><div class="overall-info"><div class="label">${esc(spec.overallLabel)}</div>
      <div class="summary">${code(spec.summary)}</div></div>
    <div class="overall-score"><div class="overall-grade grade-${spec.overallGrade}">${spec.overallGrade}</div>
      <div class="score">${esc(spec.overallScore)}</div></div></div>
  ${progression}
  ${spec.categories.map(categoryBlock).join("")}
  <footer>Generated by grade · ${esc(spec.timestamp)}</footer>
</div></body></html>`;

writeFileSync(out, html);
console.log("wrote", out);
